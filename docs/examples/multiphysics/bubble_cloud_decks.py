"""Write the bubble-cloud decks circuits/multiphysics/bubble_cloud_*.net.

  python docs/examples/multiphysics/bubble_cloud_decks.py

The paper's cloud (Smereka & Banerjee 1988, Sec. IV, Appendix): N = 199 bubbles at spacing
dx = 1 between two boundary nodes held at the imposed pressure, x = -L ... L with L = 100. Both
boundaries are one node, `pb`, so a single source drives the cloud. Interior node p<i> sits at
x = i - 100. A module-level `generate` around instances is not supported yet
(docs/token-reference.md), so the ladder is written out here instead of in Verilog-A.
"""
N, ALPHA0 = 199, 0.001
TWO_PI = 6.283185307179586


def ladder(alpha0=ALPHA0, cell=""):
    """The cloud: N cells and N + 1 links. `cell` is appended to every cell's parameters."""
    lines = []
    for i in range(1, N + 1):
        lines.append(f"XB{i} p{i} bubble alpha0={alpha0}{cell}")
    nodes = ["pb"] + [f"p{i}" for i in range(1, N + 1)] + ["pb"]
    for i in range(N + 1):
        lines.append(f"XL{i} {nodes[i]} {nodes[i + 1]} bubble_link")
    return lines


def write(name, header, sweep):
    with open(f"circuits/multiphysics/{name}", "w", encoding="utf-8", newline="\n") as f:
        f.write(header.strip("\n") + "\n")
        f.write("VP pb gnd DC 1 AC 1\n")
        f.write("\n".join(ladder()) + "\n")
        f.write(sweep + "\n.end\n")


def write_tran(name, header, omega, g, gdot, periods, alpha0=ALPHA0, mu=None, phase=0.0):
    """A transient deck: the cloud driven by p = 1 + (g + gdot t) sin(omega t) at both ends, each
    cell sampled once per period. The samples fall where the paper's p = 1 + g cos(omega t') has
    the phase `phase` (t = t' + T/4: sin is used so that the operating point is at rest)."""
    period = TWO_PI / omega
    cell = (f" mu={mu}" if mu is not None else "") + \
        f" tpoinc={period:.15g} tskip={period / 4 + phase / omega:.15g}"
    with open(f"circuits/multiphysics/{name}", "w", encoding="utf-8", newline="\n") as f:
        f.write(header.strip("\n") + "\n")
        f.write(f"XD pb bubble_drive g={g} gdot={gdot:.12g} omega={omega} nper=50\n")
        f.write("\n".join(ladder(alpha0, cell)) + "\n")
        f.write(f".tran {period / 50:.6g} {periods * period:.12g}\n.end\n")


def sweep_header(name, fig, omega, gmax, periods, alpha0, what):
    return f"""
* Bubble cloud, part 4: a slow sweep of the drive at omega = {omega} (Smereka & Banerjee 1988,
* {fig}).
*
* The 199-cell cloud of bubble_cloud_response.net (alpha0 = {alpha0}, mu = 0.002, nu = 0.015,
* L = 100), both ends driven at p = 1 + g sin(omega t), g rising from 0 to {gmax} over {periods}
* periods. Every cell prints its state once per period at the paper's phase 0 (the maximum of its
* drive): the samples of the paper's Poincare snapshots and local bifurcation diagrams.
* {what}
* Long: run it in the background through the Poincare tool, which keeps the log:
*   python scripts/poincare.py run circuits/multiphysics/{name} --model models/multiphysics/bubble --log target/bubble_sweeps/{name[:-4]}.txt -- --reltol 1e-5 --report pb
* Thresholds read off a sweep are delayed bifurcations (see bubble_ramp.net): they depend on
* the rate and on the integrator's error, and the paper states neither, so its values are a
* guide, not a target. Wall times are with all six sweeps running at once, one thread each.
* Plots: python docs/examples/multiphysics/bubble_cloud_sweeps.py
* Generated by docs/examples/multiphysics/bubble_cloud_decks.py.
"""


