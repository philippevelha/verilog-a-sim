"""Write the bubble-cloud decks circuits/multiphysics/bubble_cloud_*.net.

  python docs/examples/multiphysics/bubble_cloud_decks.py

The paper's cloud (Smereka & Banerjee 1988, Sec. IV, Appendix): N = 199 bubbles at spacing
dx = 1 between two boundary nodes held at the imposed pressure, x = -L ... L with L = 100. Both
boundaries are one node, `pb`, so a single source drives the cloud. Interior node p<i> sits at
x = i - 100. A module-level `generate` around instances is not supported yet
(docs/token-reference.md), so the ladder is written out here instead of in Verilog-A.
"""
N, ALPHA0 = 199, 0.001
TWO_PI = 6.283185307179586


def ladder():
    lines = []
    for i in range(1, N + 1):
        lines.append(f"XB{i} p{i} bubble alpha0={ALPHA0}")
    nodes = ["pb"] + [f"p{i}" for i in range(1, N + 1)] + ["pb"]
    for i in range(N + 1):
        lines.append(f"XL{i} {nodes[i]} {nodes[i + 1]} bubble_link")
    return lines


def write(name, header, sweep):
    with open(f"circuits/multiphysics/{name}", "w", encoding="utf-8", newline="\n") as f:
        f.write(header.strip("\n") + "\n")
        f.write("VP pb gnd DC 1 AC 1\n")
        f.write("\n".join(ladder()) + "\n")
        f.write(sweep + "\n.end\n")


def ac_lin(w0, w1, dw):
    n = round((w1 - w0) / dw) + 1
    return f".ac lin {n} {w0 / TWO_PI:.15g} {w1 / TWO_PI:.15g}"


write("bubble_cloud_response.net", """
* Bubble cloud, part 2a: the linear response function of a driven cloud (Smereka & Banerjee 1988,
* Sec. IV A, Fig. 8, eqs. 49-52).
*
* 199 cells of models/multiphysics/bubble/bubble_parts.va (alpha0 = 0.001, mu = 0.002,
* nu = 0.015, so b = mu + nu = 0.017) joined by bubble_links (dx = 1), both ends held at p = 1
* with a unit AC amplitude: a cloud of half-length L = 100. Generated by
* docs/examples/multiphysics/bubble_cloud_decks.py. AC frequency in Hz: omega = 2 pi f.
* The response function G is the pressure amplitude at the centre, |q(0)|/g = 1/|cosh(h L)|,
* h^2 = -3 alpha0 omega^2 / (1 - omega^2 + i b omega) (eq. 36b). Resonances at omega < 1, the
* cutoff; undamped, at eq. (52): omega_n = (1 + 12 L^2 alpha0 / (n^2 pi^2))^-1/2, n odd:
* 0.27567, 0.65220, 0.82024, 0.89510, 0.93246, ...
* What to look for (measured at 2.44.0+6): |Pb(p100)| within 5.0e-7 relative of the ladder's
*   exact solution at all 3601 points (the printout's 7 digits). Peaks, parabola-interpolated:
*   0.27567 (G = 249.2 on the grid), 0.65213 (22.0), 0.82002 (5.95), 0.89458 (2.32), 0.93106
*   (1.05), each within 1.4e-3 of eq. (52) and lower by damping. The ladder is within 6.8e-3 of
*   the paper's continuous eq. (38) below omega = 0.95 but up to 24 % off just below the cutoff,
*   where the wavelength shrinks to the grid spacing.
* Plot and check: python docs/examples/multiphysics/bubble_plots.py target/release/va-cli
* Run: va-cli sim circuits/multiphysics/bubble_cloud_response.net --model models/multiphysics/bubble --ac --report p100
""", ac_lin(0.1, 1.0, 2.5e-4))

write("bubble_cloud_profiles.net", """
* Bubble cloud, part 2b: the pressure along a driven cloud (Smereka & Banerjee 1988, eqs. 43-47,
* Figs. 5-7).
*
* The cloud of bubble_cloud_response.net, swept from omega = 0.85 to 2.0 in steps of 0.01 and
* every node reported: the steady pressure p(x, t) = 1 + g A(x) cos(omega t + Phi(x)) (eq. 48).
* Below the cutoff (omega = 0.85, Fig. 5) the cloud is spatially periodic with wavelength
* 2 pi / beta+; near it (0.97, Fig. 6) the amplitude decays within a few wavelengths; above it
* (2.0, Fig. 7) it decays as exp(-beta- |x - L|) and the core is shielded.
* What to look for (measured at 2.44.0+6): each profile within 1e-4 of the ladder's exact
*   solution (the 0.01 degree phase printout) and within 5.7e-3 of eq. (38). omega = 0.85:
*   wavelength 2 pi / beta+ = 71.2, |q(0)| = 1.161. omega = 0.97: decay at the edge 0.02898
*   (beta- = 0.02909). omega = 2.0: decay 0.06323 (beta- = 0.06324), |q(0)| = 3.59e-3.
* Generated by docs/examples/multiphysics/bubble_cloud_decks.py.
* Plot and check: python docs/examples/multiphysics/bubble_plots.py target/release/va-cli
* Run: va-cli sim circuits/multiphysics/bubble_cloud_profiles.net --model models/multiphysics/bubble --ac
""", ac_lin(0.85, 2.0, 0.01))
print("wrote circuits/multiphysics/bubble_cloud_response.net and bubble_cloud_profiles.net")
