"""Write the circuit deck for one MNIST sample: hidden 2, hidden 3 and the output layer of the
Xuan et al. (IJCNN 2026) SNN as memristor crossbars and analog neurons, driven by the spike
trains hidden 1 produced in software -- the paper's own split (Sec. IV-B).

Usage (from the repository root, after train_mnist.py):
  python circuits/snn/mnist/gen_mnist_deck.py <digit 0-9> [out.net]

Default output: circuits/snn/mnist/decks/digit<d>.net (not committed; regenerate). Run with:
  va-cli sim <deck> --model models/snn --tran --report <every h2_*, h3_*, o_* net>
(check_mnist.py runs it and reads the spikes back.)

What is in the deck:
  * word lines: hidden 1's 64 spike trains (model.json), each spike high for its whole cycle with
    1 ns edges, the waveform a neuron's own output has;
  * crossbars: one 2T2R cell (models/snn/synapse_2t2r.va) per synapse, its two RRAM levels the
    pair that realizes the synapse's quantized weight (Sec. II-C, Eq. 13). A zero weight is two
    HRS cells, so every crosspoint has a cell, as a physical crossbar does;
  * neurons: the circuit of circuits/snn/neuron.inc with the refractory chain removed (the paper
    disables the refractory period for MNIST), one subcircuit per layer, carrying that layer's K:
    K = V_s * dt / (lambda * C_M) (Eq. 3), lambda from model.json;
  * each neuron's spike output drives the next layer's word line through an ideal buffer (the E
    source in dff.inc), so layers load each other not at all -- the same as the paper's digital
    spike lines.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
T, DT, CM, VS = 250e-9, 125e-9, 998e-15, 0.1


def pwl(train):
    """PWL for a spike train: high for each spiking cycle, 1 ns edges, like a neuron's output."""
    pts = ['0 0']
    level = 0
    for k, s in enumerate(train):
        if s != level:
            t = k * T
            pts.append(f'{t * 1e9:g}n {3.3 * level:g}')
            pts.append(f'{(t + 1e-9) * 1e9:g}n {3.3 * s:g}')
            level = s
    return 'PWL(' + ' '.join(pts) + ')'


def neuron_subckt(name, k):
    return f"""
* {name}: the neuron of circuits/snn/neuron.inc, refractory chain removed, K = {k:.6g}
.subckt {name} sl spk clk qclk vref vres vth
Xin   sl vref vm clk sl_stage k={k:.9g}
CM    vm  gnd 998f IC=0
XSlk  vm  cl  qclk vswitch
CL    cl  gnd 660f IC=0
XSdis cl  gnd clk vswitch
Xcmp  vm vth cmp comparator
Xff0  cmp q0 m0 clk qclk dff
Espk  spk gnd q0 gnd 1
Xlog  q0 gnd gnd gnd gnd m0 gnd clk gnd rs hz neuron_logic refr=0
XSrst vm  vres rs vswitch
.ends
"""


def main():
    digit = int(sys.argv[1])
    model = json.load(open(os.path.join(HERE, 'model.json')))
    sample = next(s for s in model['samples'] if s['label'] == digit)
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, 'decks', f'digit{digit}.net')
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    rel = os.path.relpath(os.path.join(HERE, '..'), os.path.dirname(os.path.abspath(out)))
    rel = rel.replace(os.sep, '/')
    lams = model['lambda_V_per_S']
    ks = [VS * DT / (lam * CM) for lam in lams]
    pairs = model['codebook_pairs']
    n_cycles = model['n_cycles']
    h1 = sample['spikes'][0]                        # [cycle][neuron]

    L = [f"""* MNIST sample {sample['index']} (label {digit}) through the memristor-crossbar SNN of
* Xuan et al., IJCNN 2026 (references/, Sec. IV-B): hidden 2 -> hidden 3 -> output as circuits.
* GENERATED by circuits/snn/mnist/gen_mnist_deck.py from circuits/snn/mnist/model.json.
*
* Word lines h1_0..h1_63: hidden 1's spike trains from the software model. Spike outputs:
* h2_0..h2_63, h3_0..h3_63, o_0..o_9. {n_cycles} cycles of T = 250 ns.
* K per layer (from lambda = {', '.join(f'{l / 1e3:.3f}' for l in lams)} V/mS): {', '.join(f'{k:.4f}' for k in ks)}

.include {rel}/dff.inc
"""]
    for name, k in zip(('neuron_h2', 'neuron_h3', 'neuron_out'), ks):
        L.append(neuron_subckt(name, k))
    L.append("""
Vvp   vp   gnd  DC 1.75
Vvn   vn   gnd  DC 1.55
Vref  vref gnd  DC 1.65
Vres  vres gnd  DC 1.0
Vth   vth  gnd  DC 2.4
Vclk  clk  gnd  PULSE(0 3.3 124.5n 1n 1n 124n 250n)
Vqclk qclk gnd  PULSE(0 3.3 2n 1n 1n 119n 250n)

* --- hidden 1 spike trains (software), as word lines
""")
    for i in range(len(h1[0])):
        L.append(f'Vh1_{i} h1_{i} gnd {pwl([c[i] for c in h1])}\n')
    layers = [('h1', 'h2', 'neuron_h2'), ('h2', 'h3', 'neuron_h3'), ('h3', 'o', 'neuron_out')]
    for (src, dst, sub), codes in zip(layers, model['codes']):
        L.append(f'\n* --- crossbar {src} -> {dst}: {len(codes)} x {len(codes[0])} 2T2R cells\n')
        for j, row in enumerate(codes):
            for i, c in enumerate(row):
                p, n = pairs[c]
                L.append(f'XS_{dst}_{j}_{i} vp vn sl_{dst}_{j} {src}_{i} synapse_2t2r levp={p} levn={n}\n')
        L.append(f'\n* --- {dst} neurons\n')
        for j in range(len(codes)):
            L.append(f'XN_{dst}_{j} sl_{dst}_{j} {dst}_{j} clk qclk vref vres vth {sub}\n')
    L.append(f'\n.tran 0.5n {n_cycles * T * 1e6:g}u UIC\n.end\n')
    open(out, 'w', encoding='utf-8', newline='\n').write(''.join(L))
    print('written', out)


if __name__ == '__main__':
    main()
