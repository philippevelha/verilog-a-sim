"""The MNIST network deck (circuits/snn/mnist/decks/digitN.net) with every synapse and every
neuron at transistor level, for measuring what a transistor-level MNIST run costs.

Each 2T2R cell becomes its two RRAMs and two access NMOS, as in `fig5_access.net` (one subckt per
pair of levels, so no parameters pass through a subckt). Each layer's neuron subckt becomes the
transistor neuron of `gen_neuron.py` (all four blocks, the layer's own K), with the global nets it
needs (vdd, clkb, qclkb and the biases) added to its ports. The sources power up over 1 ns as in
`gen_neuron.py`, and clkb is clk's exact complement.

**For cost measurement, not for classification.** The network was trained with an ideal input
stage that lets V_m swing from about -6.7 V to +8.7 V (circuits/snn/mnist/README.md); here V_m is
bounded by the supply, so the spikes, and with them the switching activity that sets the
timepoint count, will differ from the behavioural run's. The input stage's trim (vbs) is the one
found at K = 0.696; the sink scales with 1/K like the mirror, so it holds to first order only.

    python circuits/snn/transistor/gen_mnist_tx.py --digit 0 --cycles 2
    va-cli sim circuits/snn/transistor/mnist_tx_digit0.net --model models/snn \\
        --model models/sg13g2/psp103/psp103.va --tran --report clk,o_0

The generated decks are large (~45 000 lines) and are not committed.
"""
import argparse
import json
import os
import re

import gen_neuron as gn
import input_stage
import tech

HERE = os.path.dirname(os.path.abspath(__file__))
MNIST = os.path.join(HERE, "..", "mnist", "decks")
T = 250e-9
EXTRA_PORTS = ["clkb", "qclkb", "vdd", "vbn"] + list(input_stage.BIAS)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--digit", type=int, default=0)
    ap.add_argument("--cycles", type=float, default=None,
                    help="simulate this many 250 ns cycles instead of the deck's 29")
    ap.add_argument("--tech", default="sg13g2_hv")
    ap.add_argument("--out", default=None)
    ap.add_argument("--neurons", choices=["tx", "behavioural"], default="tx",
                    help="the neurons as transistors (default) or the behavioural blocks; the "
                         "synapses' access devices are transistors either way")
    ap.add_argument("--synapses", choices=["tx", "fit", "fitc", "ideal"], default="tx",
                    help="the synapses' access devices: transistors (default); synapse_2t2r_mos.va "
                         "with switch_fit.json's parameters (rung A); rram + mos_switch.va with the "
                         "gate's charge (rung C, which keeps each cell node); or the behavioural "
                         "deck's own synapse_2t2r.va (the 10 Ohm switch)")
    ap.add_argument("--layers", default="h2,h3,o",
                    help="which layers to keep (h2, h3, o); a synapse is kept only if its "
                         "source spike train exists")
    ap.add_argument("--per-layer", type=int, default=None,
                    help="keep only the first N neurons of each kept layer (a smaller crossbar)")
    a = ap.parse_args()
    t = tech.get(a.tech)
    src = open(os.path.join(MNIST, f"digit{a.digit}.net")).read().splitlines()
    out_path = a.out or os.path.join(HERE, f"mnist_tx_digit{a.digit}.net")

    tstop = 29 * T
    for line in src:
        m = re.match(r"^\.tran\s+\S+\s+([\d.]+)u", line)
        if m:
            tstop = float(m.group(1)) * 1e-6
    if a.cycles is not None:
        tstop = a.cycles * T

    out = [
        f"* GENERATED by circuits/snn/transistor/gen_mnist_tx.py from digit{a.digit}.net -- do not edit.",
        f"* Neurons: {a.neurons}; synapses' access devices: {a.synapses} "
        f"({t.name} where transistors; cost measurement, see the generator).",
    ]
    if a.synapses == "tx" or a.neurons == "tx":
        out.append(".include tech.inc")
    fit = ""
    if a.synapses in ("fit", "fitc"):
        sw = json.load(open(os.path.join(HERE, "switch_fit.json")))
        fit = f" beta={sw['beta']!r} vt={sw['vt']!r} ns={sw['ns']!r}"
    if a.synapses == "fitc":
        # rung C: each path is its cell and a charged switch, so the cell node stays, and the
        # gate's charge on the drain side lands on it as in the transistor deck
        for p in range(4):
            for n in range(4):
                out += [
                    f".subckt sync_p{p}_n{n} vp vn sl wl",
                    f"XGp vp cp rram level={p}",
                    f"XAp cp sl wl mos_switch{fit} cov={sw['cov']!r} cch={sw['cch']!r}",
                    f"XGn vn cn rram level={n}",
                    f"XAn cn sl wl mos_switch{fit} cov={sw['cov']!r} cch={sw['cch']!r}",
                    ".ends",
                ]
    # 16 synapse cells, one per (levp, levn).
    for p in range(4 if a.synapses == "tx" else 0):
        for n in range(4):
            out += [
                f".subckt syn_p{p}_n{n} vp vn sl wl",
                f"XGp vp cp rram level={p}",
                t.nmos("Ap", "cp", "wl", "sl", "gnd", *gn.ACCESS),
                f"XGn vn cn rram level={n}",
                t.nmos("An", "cn", "wl", "sl", "gnd", *gn.ACCESS),
                ".ends",
            ]

    layers = set(a.layers.split(","))

    def keep(net):
        """Whether neuron `net` (h2_5, o_3, ...) is in the kept part of the network."""
        layer, idx = net.rsplit("_", 1)
        return layer in layers and (a.per_layer is None or int(idx) < a.per_layer)

    i = 0
    n_syn = n_neuron = 0
    while i < len(src):
        line = src[i]
        if line.startswith(".include"):
            if a.neurons == "behavioural":
                out.append(".include ../dff.inc")
            i += 1
            continue
        m = re.match(r"^\.subckt\s+(neuron_\w+)\s+(.*)$", line)
        if m:
            name, ports = m.group(1), m.group(2)
            body = []
            i += 1
            while not src[i].startswith(".ends"):
                body.append(src[i])
                i += 1
            k = next(re.search(r"k=([\d.]+)", b).group(1) for b in body if b.startswith("Xin "))
            if a.neurons == "behavioural":
                out += [line] + body + [src[i]]
            else:
                out.append(f".subckt {name} {ports} {' '.join(EXTRA_PORTS)}")
                out += gn.neuron(t, set(gn.BLOCKS), k)
                out.append(".ends")
            i += 1
            continue
        m = re.match(r"^(XS_\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+synapse_2t2r\s+levp=(\d)\s+levn=(\d)", line)
        if m:
            inst, vp, vn, sl, wl, p, n = m.groups()
            if not (keep(sl[3:]) and (wl.startswith("h1_") or keep(wl))):
                i += 1
                continue
            if a.synapses == "tx":
                out.append(f"{inst} {vp} {vn} {sl} {wl} syn_p{p}_n{n}")
            elif a.synapses == "fitc":
                out.append(f"{inst} {vp} {vn} {sl} {wl} sync_p{p}_n{n}")
            elif a.synapses == "fit":
                out.append(f"{inst} {vp} {vn} {sl} {wl} synapse_2t2r_mos levp={p} levn={n}{fit}")
            else:
                out.append(line)
            n_syn += 1
            i += 1
            continue
        if re.match(r"^XN_\S+ .* neuron_\w+\s*$", line):
            parts = line.split()
            if not keep(parts[2]):
                i += 1
                continue
            extra = EXTRA_PORTS if a.neurons == "tx" else []
            out.append(" ".join(parts[:-1] + extra + parts[-1:]))
            n_neuron += 1
            i += 1
            continue
        if line.startswith("Vqclk "):
            out.append(line)
            out.append("Vqclkb qclkb gnd PULSE(0 3.3 122n 1n 1n 129n 250n)")
            out.append(gn.complement("Vclkb", "clkb", 124.5e-9, 124e-9, T, tstop))
            out.append(gn.power_up("Vdd   vdd  gnd  DC 3.3"))
            out.append(gn.power_up("Vbn   vbn  gnd  DC 0.8"))
            for name, v in input_stage.BIAS.items():
                out.append(gn.power_up(f"V{name:<5} {name:<5} gnd DC {v}"))
            i += 1
            continue
        if line.startswith(".tran"):
            out.append(f".tran 0.5n {tstop * 1e9:g}n UIC")
            i += 1
            continue
        out.append(gn.power_up(line))
        i += 1

    with open(out_path, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    t.write_inc(os.path.join(os.path.dirname(out_path), "tech.inc"))
    per_neuron = sum(1 for l in gn.neuron(t, set(gn.BLOCKS), "1") if " hv" in l)
    n_mos = (2 * n_syn if a.synapses == "tx" else 0) + (n_neuron * per_neuron if a.neurons == "tx" else 0)
    print(f"wrote {out_path}: {n_syn} synapses, {n_neuron} neurons, {n_mos} PSP103, "
          f"{tstop * 1e9:g} ns")


if __name__ == "__main__":
    main()
