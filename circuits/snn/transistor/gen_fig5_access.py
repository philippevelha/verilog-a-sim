"""Fig. 5 deck (circuits/snn/fig5_neuron.net) with the 2T2R access switches as real MOS devices.

Everything else is unchanged: the neuron is still the behavioural one (sl_stage, comparator,
vswitch flip-flops). Each `XA.. <cell> sl <wl> vswitch ron=10` line becomes an NMOS with its
drain on the cell, source on the source line, gate on the word line and bulk at ground.

    python circuits/snn/transistor/gen_fig5_access.py [--w 10e-6] [--l 0.45e-6] [--tech sg13g2_hv]
    va-cli sim circuits/snn/transistor/fig5_access.net --model models/snn \
        --model models/sg13g2/psp103/psp103.va --tran --report clk,wl1,vm,spk

`--switch fit` writes fig5_fit.net instead: every access switch is mos_switch.va with the
parameters fit_switch.py stored in switch_fit.json (rung A, no transistor model needed).
`--switch fitc` writes fig5_fitc.net, the same with the gate's charge (rung C), and `--switch
fitbc` writes fig5_fitbc.net, rung C plus the gate drive's V_DS term (rung B):

    python circuits/snn/transistor/gen_fig5_access.py --switch fit
    va-cli sim circuits/snn/transistor/fig5_fit.net --model models/snn --tran \
        --report clk,wl1,vm,spk
"""
import argparse
import json
import os
import re

import tech

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "fig5_neuron.net")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--w", type=float, default=10e-6, help="access transistor width (m)")
    ap.add_argument("--l", type=float, default=0.45e-6, help="access transistor length (m)")
    ap.add_argument("--tech", default="sg13g2_hv")
    ap.add_argument("--switch", choices=["psp103", "fit", "fitc", "fitbc"], default="psp103",
                    help="the access switch: the transistor (default), or mos_switch.va with "
                         "switch_fit.json's parameters, without (fit, rung A) or with (fitc, "
                         "rung C) the gate's charge, or with the charge and the V_DS term (fitbc, "
                         "rungs B and C)")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    if a.switch in ("fit", "fitc", "fitbc"):
        return write_fit(a.out or os.path.join(HERE, f"fig5_{a.switch}.net"),
                         a.switch != "fit", a.switch == "fitbc")
    a.out = a.out or os.path.join(HERE, "fig5_access.net")
    t = tech.get(a.tech)

    out = [
        f"* GENERATED by circuits/snn/transistor/gen_fig5_access.py -- do not edit.",
        f"* circuits/snn/fig5_neuron.net with every 2T2R access switch an {t.name} NMOS,",
        f"* W = {a.w * 1e6:g} um, L = {a.l * 1e6:g} um, bulk at ground. The neuron is unchanged",
        f"* (behavioural).",
        "*",
        f"*   va-cli sim {os.path.relpath(a.out, os.path.join(HERE, '..', '..', '..'))} "
        "--model models/snn " + " ".join(f"--model {m}" for m in t.model_args())
        + " --tran --report clk,wl1,vm,spk",
        ".include tech.inc",
    ]
    n = 0
    with open(SRC) as fh:
        for line in fh:
            line = line.rstrip("\n")
            m = re.match(r"^(XA\w+)\s+(\S+)\s+(\S+)\s+(\S+)\s+vswitch\b", line)
            if m:
                inst, cell, sl, wl = m.groups()
                out.append(t.nmos(inst[1:], cell, wl, sl, "gnd", a.w, a.l))
                n += 1
            elif line.startswith(".include "):
                out.append(".include ../" + line.split()[1])
            else:
                out.append(line)
    if n == 0:
        raise SystemExit("no access switch found in " + SRC)
    with open(a.out, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    t.write_inc(os.path.join(os.path.dirname(a.out), "tech.inc"))
    print(f"wrote {a.out}: {n} access transistors")


def switch_params(fit, charge, vds):
    """mos_switch.va's instance parameters from switch_fit.json: rung A, rung C (charge) or
    rungs B and C (vds: kds, with the vt and charge fitted alongside it)."""
    if vds:
        return (f"beta={fit['beta']!r} vt={fit['vt_b']!r} ns={fit['ns']!r} kds={fit['kds']!r} "
                f"cov={fit['cov_b']!r} cch={fit['cch_b']!r}")
    params = f"beta={fit['beta']!r} vt={fit['vt']!r} ns={fit['ns']!r}"
    if charge:
        params += f" cov={fit['cov']!r} cch={fit['cch']!r}"
    return params


def write_fit(out_path, charge=False, vds=False):
    fit = json.load(open(os.path.join(HERE, "switch_fit.json")))
    params = switch_params(fit, charge, vds)
    rung = ("rungs B and C, with the V_DS term and the gate's charge" if vds else
            "rung C, with the gate's charge" if charge else "rung A")
    name = os.path.basename(out_path)
    out = [
        f"* GENERATED by circuits/snn/transistor/gen_fig5_access.py --switch "
        f"{'fitbc' if vds else 'fitc' if charge else 'fit'} -- do not edit.",
        "* circuits/snn/fig5_neuron.net with every 2T2R access switch mos_switch.va, fitted to",
        f"* the {fit['device']}",
        f"* (switch_fit.json, {rung}). The neuron is unchanged (behavioural).",
        "*",
        f"*   va-cli sim circuits/snn/transistor/{name} --model models/snn --tran "
        "--report clk,wl1,vm,spk",
    ]
    n = 0
    with open(SRC) as fh:
        for line in fh:
            line = line.rstrip("\n")
            m = re.match(r"^(XA\w+)\s+(\S+)\s+(\S+)\s+(\S+)\s+vswitch\b", line)
            if m:
                inst, cell, sl, wl = m.groups()
                out.append(f"{inst} {cell} {sl} {wl} mos_switch {params}")
                n += 1
            elif line.startswith(".include "):
                out.append(".include ../" + line.split()[1])
            else:
                out.append(line)
    if n == 0:
        raise SystemExit("no access switch found in " + SRC)
    with open(out_path, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {out_path}: {n} fitted access switches")


if __name__ == "__main__":
    main()
