"""The technology layer of the transistor-level SNN decks: every MOS device goes through here.

A deck generator asks a `Tech` for device lines (`nmos(...)`, `pmos(...)`); the `Tech` writes
one `.model` card per distinct geometry into the deck's `tech.inc` and says which Verilog-A
library the cards need (`model_args`). Changing the process is changing the backend, not the
decks: when the foundry's SG13S + MEMRES models arrive, they become one more backend here.

Backends:
  sg13g2_hv  IHP SG13G2 open PDK, thick-oxide 3.3 V devices (sg13_hv_nmos / sg13_hv_pmos),
             typical corner, PSP103 (models/sg13g2/). The SNN's own process is SG13S, the same
             IHP 130 nm platform; SG13G2 is its public sibling, not the same process.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


class Sg13g2Hv:
    """IHP SG13G2 HV MOS through PSP103. Valid range (PDK): L >= 0.45 um (n), 0.40 um (p);
    W 0.30..10 um per finger."""

    name = "sg13g2_hv"
    lmin = {"nmos": 0.45e-6, "pmos": 0.40e-6}

    def __init__(self, corner="mos_tt"):
        sys.path.insert(0, os.path.join(ROOT, "models", "sg13g2"))
        import sg13g2_cards  # noqa: E402

        self._cards = sg13g2_cards
        self.corner = corner
        self._models = {}  # model name -> card text
        self._inst = {}  # model name -> instance parameters

    def _device(self, kind, inst, d, g, s, b, w, l, ng):
        if l < self.lmin[kind]:
            raise ValueError(f"{inst}: L={l} below the PDK's {kind} minimum {self.lmin[kind]}")
        if w / ng > 10e-6:
            raise ValueError(f"{inst}: {w / ng} m per finger, above the PDK's 10 um; raise ng")
        name, text, params = self._cards.card(kind, w, l, ng, corner=self.corner)
        self._models.setdefault(name, text)
        self._inst[name] = params
        return f"X{inst} {d} {g} {s} {b} {name} {params}"

    def nmos(self, inst, d, g, s, b, w, l, ng=1):
        return self._device("nmos", inst, d, g, s, b, w, l, ng)

    def pmos(self, inst, d, g, s, b, w, l, ng=1):
        return self._device("pmos", inst, d, g, s, b, w, l, ng)

    def write_inc(self, path):
        with open(path, "w", newline="\n") as fh:
            fh.write(f"* {self.name}, corner {self.corner}: generated by circuits/snn/transistor/"
                     "tech.py from the IHP Open PDK (Apache-2.0). Do not edit.\n")
            for text in self._models.values():
                fh.write(text + "\n")

    def model_args(self):
        """The `--model` arguments a deck using this technology needs, besides models/snn."""
        return ["models/sg13g2/psp103/psp103.va"]


BACKENDS = {"sg13g2_hv": Sg13g2Hv}


def get(name="sg13g2_hv", **kw):
    return BACKENDS[name](**kw)
