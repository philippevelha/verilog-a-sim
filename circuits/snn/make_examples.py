"""Regenerate docs/examples/snn_memristor/ from the decks and models that are actually run.

Usage (from the repository root):
  python circuits/snn/make_examples.py [path/to/va-cli]

For each figure it:
  1. runs the deck (circuits/snn/fig*_neuron.net) with va-cli and keeps the output;
  2. writes the deck flattened -- every `.include` inlined -- as one reviewable netlist, runs that
     too, and fails unless its output is byte-identical to the original deck's;
  3. plots the waveforms with `va-cli --plot` (SVG) and the per-timestep comparison with
     check_snn.py (PNG), which also re-runs the pass/fail check;
and then writes README.md: the results, both flattened netlists, and every Verilog-A model
source in full. Nothing in the output folder is edited by hand; rerun this after any change.
"""
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SNN = os.path.join(ROOT, 'circuits', 'snn')
MODELS = os.path.join(ROOT, 'models', 'snn')
OUT = os.path.join(ROOT, 'docs', 'examples', 'snn_memristor')

FIGS = [
    ('fig4', 'clk,wl,vm,spk', 'Fig. 4: five identical synapses, refractory 1 us'),
    ('fig5', 'clk,wl1,wl2,wl3,wl4,vm,spk', 'Fig. 5: four codebook synapses, circuit vs snnTorch'),
]


def flatten(path):
    """The deck with each `.include <file>` replaced by that file, marked where it came from."""
    out = []
    for line in open(path, encoding='utf-8'):
        m = re.match(r'\s*\.include\s+(\S+)', line, re.I)
        if m:
            inc = os.path.join(os.path.dirname(path), m.group(1))
            out.append(f'* ===== begin {m.group(1)} (circuits/snn/{m.group(1)}) =====\n')
            out.extend(open(inc, encoding='utf-8').readlines())
            out.append(f'* ===== end {m.group(1)} =====\n')
        else:
            out.append(line)
    return ''.join(out)


def run(va, deck, report, extra=()):
    r = subprocess.run([va, 'sim', deck, '--model', MODELS, '--tran', '--report', report, *extra],
                       capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        raise SystemExit(f'va-cli failed on {deck}:\n{r.stderr}')
    return r.stdout


def main():
    va = (os.path.abspath(sys.argv[1]) if len(sys.argv) > 1
          else os.path.join(ROOT, 'target', 'release', 'va-cli'))
    os.makedirs(OUT, exist_ok=True)
    results = {}
    for fig, report, _ in FIGS:
        deck = os.path.join(SNN, f'{fig}_neuron.net')
        text = run(va, deck, report)
        flat = os.path.join(OUT, f'{fig}_neuron_full.net')
        header = (f'* GENERATED by circuits/snn/make_examples.py from circuits/snn/{fig}_neuron.net\n'
                  f'* with every .include inlined. Do not edit; edit the source deck and rerun.\n'
                  f'* Run: va-cli sim {os.path.relpath(flat, ROOT).replace(os.sep, "/")} '
                  f'--model models/snn --tran --report {report}\n*\n')
        open(flat, 'w', encoding='utf-8', newline='\n').write(header + flatten(deck))
        flat_text = run(va, flat, report)
        strip = lambda s: '\n'.join(l for l in s.splitlines() if not l.startswith('[va-cli]'))
        if strip(flat_text) != strip(text):
            raise SystemExit(f'{fig}: the flattened netlist does not reproduce the deck')
        digest = hashlib.sha256(strip(text).encode()).hexdigest()[:16]
        outfile = os.path.join(OUT, f'{fig}.out')
        open(outfile, 'w', encoding='utf-8', newline='\n').write(text)
        run(va, deck, 'vm,spk', ['--plot', os.path.join(OUT, f'{fig}_vm_spike.svg')])
        chk = subprocess.run([sys.executable, os.path.join(SNN, 'check_snn.py'), fig, outfile,
                              '--plot', os.path.join(OUT, f'{fig}_vs_paper.png')],
                             capture_output=True, text=True, cwd=ROOT)
        results[fig] = (chk.returncode, chk.stdout.replace(OUT, 'docs/examples/snn_memristor'),
                        digest)
        os.remove(outfile)
    cb = subprocess.run([sys.executable, os.path.join(SNN, 'check_snn.py'), 'codebook'],
                        capture_output=True, text=True, cwd=ROOT)
    write_readme(results, cb.stdout)
    bad = [f for f, (rc, _, _) in results.items() if rc != 0] + (['codebook'] if cb.returncode else [])
    print('written to', OUT, '; failed:', bad or 'none')
    sys.exit(1 if bad else 0)


def write_readme(results, codebook):
    L = ['# Memristor-crossbar spiking neuron: review page', '',
         '**Generated** by `circuits/snn/make_examples.py`; do not edit by hand. It reproduces the',
         'neuron-level results of Xuan et al., IJCNN 2026 (`references/`); the reasoning, the',
         "choices the paper leaves open, and the limitations are in `circuits/snn/README.md`.", '',
         'Everything below is what was run: the flattened netlists are the decks with their',
         '`.include` files inlined, and each was checked to give byte-identical output to its',
         'source deck. **No transistor models are involved**: the circuit is built at the level of',
         "the paper's functional diagram (its Fig. 3) from the Verilog-A models listed at the end",
         '(RRAM cell, switch, op-amp/attenuator stage, comparator, gating logic) and SPICE',
         'primitives (C, E, V). The paper\'s IHP SG13S/MEMRES process is not public and it gives no',
         'device sizes.', '']
    for fig, report, title in FIGS:
        rc, out, digest = results[fig]
        L += [f'## {title}', '',
              f'![{fig} waveforms]({fig}_vm_spike.svg)', '',
              f'`{fig}_vm_spike.svg`: V_m and the output spike from `va-cli --plot`.', '',
              f'![{fig} vs paper]({fig}_vs_paper.png)', '',
              f'`{fig}_vs_paper.png`: the clock, input and output in continuous time, then V_m',
              'at each latch edge against the paper\'s equations (and, for Fig. 5, the paper\'s own',
              'model and transistor-level values).', '',
              f'Check ({"PASS" if rc == 0 else "FAIL"}; output digest `{digest}`):', '',
              '```', out.rstrip(), '```', '']
    L += ['## Synapse codebook (Sec. II-C)', '', '```', codebook.rstrip(), '```', '']
    for fig, _, title in FIGS:
        L += [f'## Netlist: `{fig}_neuron_full.net`', '', '```spice',
              open(os.path.join(OUT, f'{fig}_neuron_full.net'), encoding='utf-8').read().rstrip(),
              '```', '']
    L += ['## Verilog-A models (`models/snn/`)', '']
    for f in sorted(os.listdir(MODELS)):
        if f.endswith('.va'):
            L += [f'### `{f}`', '', '```verilog',
                  open(os.path.join(MODELS, f), encoding='utf-8').read().rstrip(), '```', '']
    open(os.path.join(OUT, 'README.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L))


if __name__ == '__main__':
    main()
