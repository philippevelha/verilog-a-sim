#!/usr/bin/env python3
"""Run every validation test of the microwave-photonics library and write RESULTS.md.

    python run_all.py            # all tests, about 6 minutes (the OEO and the noise comparison are most of it)
    python run_all.py t03 t07    # a subset, by prefix

Each test is a script that prints its checks, writes <test>.json, and is run here in its own
process. RESULTS.md is generated from the JSON files: every number in it comes from this run.
Exit status 0 only if every check of every test passed.
"""
import glob, json, os, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
TITLES = {
    "t01": "IMDD link: transfer curve, response, two-tone IMD3, noise, NF, SFDR",
    "t02": "RF processing: microring spectrum and single-passband MWP filter",
    "t03": "RF carrier generation: heterodyne 1-100 GHz, x2/x4 multiplication, linewidth",
    "t04": "Opto-electronic oscillator: frequency, amplitude, mode selection",
    "t05": "Waveform generation: 16-QAM at 20 GHz, 4 GHz linear-FM chirp",
    "t06": "Optical sampling: pulse energies, linearisation, jitter, 1:2 demultiplexing",
    "t07": "Beamforming: dispersive true-time delay, RF phase shifter, switched delay, ring delay",
    "t08": "Mixing: dual-series and carrier-suppressed dual-parallel MZM down-converters",
    "t09": "Dispersion inside the band: all-pass chain against the fibre fading curve",
    "t10": "Optical amplifier: gain saturation, signal-spontaneous beat noise",
    "t11": "Noise in the time domain: library module against the simulator's --tran-noise",
    "t12": "Golden reference: verilog-a-sim against Cadence Spectre's committed outputs",
}


def fmt(x):
    return f"{x:.6g}"


def main():
    want = sys.argv[1:]
    scripts = sorted(glob.glob(os.path.join(HERE, "t[0-9][0-9]_*.py")))
    scripts = [s for s in scripts if not want or any(os.path.basename(s).startswith(w) for w in want)]
    version = subprocess.run([sys.executable, "-c", "import mwp, subprocess; print(mwp.VACLI)"], cwd=HERE,
                             capture_output=True, text=True).stdout.strip()
    all_ok, t0 = True, time.time()
    for s in scripts:
        p = subprocess.run([sys.executable, s], cwd=HERE)
        all_ok &= p.returncode == 0
    md = ["# Validation results", "",
          "Generated by `tests/run_all.py`; every number below is from that run. `sim` is the simulator,",
          "`ref` the closed form named in the check, `err` their relative (rel) or absolute (abs) difference.", ""]
    n_checks = n_pass = 0
    summary = ["| Test | What | Checks | Result | Time (s) |", "|---|---|---|---|---|"]
    body = []
    for s in sorted(glob.glob(os.path.join(HERE, "t[0-9][0-9]_*.json"))):
        d = json.load(open(s))
        rows = [r for r in d["rows"] if "what" in r]
        ok = sum(r["ok"] for r in rows)
        n_checks += len(rows); n_pass += ok
        key = d["test"][:3]
        status = "skipped (no data)" if d.get("skipped") else ("pass" if d["ok"] else "**FAIL**")
        summary.append(f"| `{d['test']}` | {TITLES.get(key, '')} | {ok}/{len(rows)} | {status} | {d['wall_s']} |")
        body += ["", f"## {d['test']} - {TITLES.get(key, '')}", "", "| Check | sim | ref | err | tol | |", "|---|---|---|---|---|---|"]
        for r in d["rows"]:
            if "note" in r:
                body.append(f"| _{r['note'].strip()}_ | | | | | |")
            else:
                body.append(f"| {r['what']} | {fmt(r['sim'])} {r['unit']} | {fmt(r['ref'])} | {r['err']:.1e} {'rel' if r['rel'] else 'abs'} "
                            f"| {r['tol']:g} | {'ok' if r['ok'] else '**FAIL**'} |")
    md += summary + ["", f"**{n_pass} of {n_checks} checks pass.**"] + body + [""]
    with open(os.path.join(os.path.dirname(HERE), "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md))
    print(f"\n{n_pass}/{n_checks} checks pass over {len(scripts)} test(s) in {time.time() - t0:.0f} s -> RESULTS.md")
    print(f"simulator: {version}")
    return 0 if all_ok and n_pass == n_checks else 1


if __name__ == "__main__":
    sys.exit(main())
