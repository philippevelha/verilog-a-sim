#!/usr/bin/env python3
"""Write mrm_pin_eq4.va: mrm_pin.va with the ring written as Wang 2016 Eq. (4), the delayed-feedback
(round-trip) form, instead of the TCMT form. Everything before the ring section - the p-i-n network,
the free carriers, the plasma dispersion, the heater - is copied unchanged, so the two models differ
only in how the ring is written. Needs absdelay() in transient (verilog-a-sim >= 2.44.0; OpenVAF
does not support absdelay).

All-pass ring, fields in sqrt(mW), c = ring field just after the coupler:
    c(t)   = j kappa E_in(t) + sigma a(t) e^{j Phi(t)} c(t - tau_res)
    E_t(t) = sigma E_in(t)   + j kappa a(t) e^{j Phi(t)} c(t - tau_res)
which in steady state is Eq. (5), T = sigma - kappa^2 a e^{j Phi} / (1 - sigma a e^{j Phi}).
a(t) and Phi(t) are the TCMT model's own: a = exp(-inv_ti tau_res), Phi = dw tau_res (the round-trip
phase offset from resonance, so that a delay map with this Phi is the TCMT ring to first order in
tau_res). The drop port and the absorbed-power term of self-heating are not written in this form
(both are off by default in mrm_pin.va: sigma_d = 1, self_heat = 0).

    python3 make_eq4.py         # reads ../mrm_pin.va, writes mrm_pin_eq4.va here
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "..", "mrm_pin.va")).read()


def rep(old, new):
    global src
    assert src.count(old) == 1, old[:60]
    src = src.replace(old, new)


rep("module mrm_pin(", "module mrm_pin_eq4(")
rep("    electrical yr, yi;               // cavity field (sqrt(mW))",
    "    electrical ur, ui;               // ring field after the coupler, c (sqrt(mW))\n"
    "    electrical qr, qi;               // c(t - tau_res), the delayed ring field")
i = src.index("        sr  = V(o_in_re);   si  = V(o_in_im);")
j = src.index("        // ===================== thermal balance =====================")
src = src[:i] + """        sr  = V(o_in_re);   si  = V(o_in_im);
        // ring as Wang 2016 Eq. (4): the field after one round trip, delayed by tau_res.
        V(qr) <+ absdelay(V(ur), tres);
        V(qi) <+ absdelay(V(ui), tres);
        a_rt = exp(-inv_ti * tres);
        phi  = dw * tres;
        kap  = sqrt(1.0 - sigma * sigma);
        p_r  = a_rt * (cos(phi) * V(qr) - sin(phi) * V(qi));     // a e^{j phi} c(t - tau_res)
        p_i  = a_rt * (cos(phi) * V(qi) + sin(phi) * V(qr));
        V(ur) <+ -kap * si + sigma * p_r;
        V(ui) <+  kap * sr + sigma * p_i;

        tl = pow(10.0, -ilossdB / 20.0);
        V(o_thru_re) <+ tl * (sigma * sr - kap * p_i);
        V(o_thru_im) <+ tl * (sigma * si + kap * p_r);
        V(o_drop_re) <+ 0.0;
        V(o_drop_im) <+ 0.0;

""" + src[j:]
rep("        P_abs = f_abs * (inv_ti / inv_tc) * (y_r * y_r + y_i * y_i) * 1.0e-3;",
    "        P_abs = 0.0;   // not written in the Eq. (4) form (see the header of make_eq4.py)")
# the new locals
k = src.index("    real sr, si, y_r, y_i,")
src = src[:k] + "    real a_rt, phi, kap, p_r, p_i;\n" + src[k:]
src = ("// GENERATED by tests/make_eq4.py from ../mrm_pin.va: the ring in Wang 2016 Eq. (4) form.\n"
       "// Do not edit; edit mrm_pin.va or make_eq4.py and regenerate.\n") + src
open(os.path.join(HERE, "mrm_pin_eq4.va"), "w", newline="\n").write(src)
print("wrote mrm_pin_eq4.va")
